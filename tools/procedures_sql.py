#!/usr/bin/env python3
"""The procedures table's seed rows, generated from the registry (ai-hq job platform-directory-0033, procedure registry
job 2 of 4). The registry is the source; the database's rows are generated from it (plan review item 4).

  python3 tools/procedures_sql.py            # rewrite the seed block in supabase/schema.sql from content/procedure-keys.json
  python3 tools/procedures_sql.py --check    # what the build runs: exit 1 if any seed differs from the registry
  python3 tools/procedures_sql.py --new FILE # write a new migration seeding the issued keys no migration seeds yet

A seed block sits between the two marker lines below. Rules the build checks (check()):
  - supabase/schema.sql (a fresh database) seeds exactly the issued keys, in issued order;
  - the migrations, taken together, seed every issued key exactly once and nothing else.
An applied migration never changes (scripts/eo_db_apply.py refuses a changed checksum), so a new key gets a new
migration file from --new rather than an edit to an old one.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BEGIN = "-- BEGIN GENERATED SEED: tools/procedures_sql.py from content/procedure-keys.json. Edit that file, not this block."
END = "-- END GENERATED SEED"
BLOCK = re.compile(re.escape(BEGIN) + r"\n(.*?)" + re.escape(END), re.S)
KEY = re.compile(r"\('([a-z][a-z0-9]{1,15})'\)")


def issued(root=ROOT):
    import json
    return json.loads((root / "content" / "procedure-keys.json").read_text(encoding="utf-8"))["issued"]


def seed(keys):
    """The block's body: one insert, safe to run twice."""
    vals = ", ".join(f"('{k}')" for k in keys)
    return f"insert into procedures (key) values {vals}\n  on conflict (key) do nothing;\n"


def block(keys):
    return BEGIN + "\n" + seed(keys) + END


def seeded(text):
    """Keys seeded by the blocks in text, in order; None if the file has no block."""
    bodies = BLOCK.findall(text)
    if not bodies:
        return None
    return [k for b in bodies for k in KEY.findall(b)]


def check(root=ROOT):
    errs, keys = [], issued(root)
    schema = (root / "supabase" / "schema.sql").read_text(encoding="utf-8")
    got = seeded(schema)
    if got != keys:
        errs.append(f"supabase/schema.sql seeds {got} but content/procedure-keys.json issues {keys}: run python3 tools/procedures_sql.py")
    for b in BLOCK.findall(schema):
        if b != seed(keys):
            errs.append("supabase/schema.sql: the seed block was edited by hand: run python3 tools/procedures_sql.py")
    every = []
    for f in sorted((root / "supabase" / "migrations").glob("*.sql")):
        text = f.read_text(encoding="utf-8")
        got = seeded(text)
        if got is None:
            continue
        for b in BLOCK.findall(text):
            if b != seed(KEY.findall(b)):
                errs.append(f"supabase/migrations/{f.name}: the seed block was edited by hand")
        every += got
    dup = sorted({k for k in every if every.count(k) > 1})
    if dup:
        errs.append(f"supabase/migrations: keys seeded more than once {dup}")
    extra = [k for k in every if k not in keys]
    if extra:
        errs.append(f"supabase/migrations seed keys the registry never issued {extra}")
    missing = [k for k in keys if k not in every]
    if missing:
        errs.append(f"supabase/migrations seed no row for issued keys {missing}: run python3 tools/procedures_sql.py --new supabase/migrations/<date>-procedures-<key>.sql")
    return errs


def write_schema(root=ROOT):
    p = root / "supabase" / "schema.sql"
    text = p.read_text(encoding="utf-8")
    if seeded(text) is None:
        raise SystemExit("supabase/schema.sql has no seed block to rewrite")
    new = BLOCK.sub(lambda m: block(issued(root)), text)
    if new != text:
        p.write_text(new, encoding="utf-8")
    return new != text


def new_migration(path, root=ROOT):
    every = []
    for f in sorted((root / "supabase" / "migrations").glob("*.sql")):
        every += seeded(f.read_text(encoding="utf-8")) or []
    keys = [k for k in issued(root) if k not in every]
    if not keys:
        raise SystemExit("every issued key is seeded already: no migration needed")
    pathlib.Path(path).write_text(
        f"-- Procedure rows for {', '.join(keys)}, generated by tools/procedures_sql.py. Apply with scripts/eo_db_apply.py (ai-hq)\n"
        "-- before the site lists the procedure. Safe to run twice.\n" + block(keys) + "\n", encoding="utf-8")
    return keys


def main(argv):
    if argv[:1] == ["--check"]:
        errs = check()
        for e in errs:
            print("procedures seed:", e, file=sys.stderr)
        return 1 if errs else 0
    if argv[:1] == ["--new"] and len(argv) == 2:
        print("seeded", new_migration(argv[1]))
        return 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    print("supabase/schema.sql", "rewritten" if write_schema() else "already matches")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
